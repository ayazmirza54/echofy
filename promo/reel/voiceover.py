"""Generates the voiceover with Kokoro (open-source neural TTS, runs locally).

Each caption in timeline.js is spoken starting at its `s` time. Writes:
  <outdir>/voiceover.wav   the full-length VO track (mono, 24 kHz)
  vo_timing.js             spoken duration of each line, so the captions'
                           word reveal (scene.html, srt.cjs) follows the voice

Usage: python voiceover.py <outdir>
Needs: pip install kokoro-onnx soundfile, plus kokoro-v1.0.onnx and
voices-v1.0.bin (github.com/thewh1teagle/kokoro-onnx releases) in
$KOKORO_DIR (default: this folder).
"""

import json
import os
import subprocess
import sys

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

HERE = os.path.dirname(os.path.abspath(__file__))


def load_timeline():
    js = "require(process.argv[1]); process.stdout.write(JSON.stringify(TL))"
    out = subprocess.check_output(["node", "-e", js, os.path.join(HERE, "timeline.js")])
    return json.loads(out)


def trim(audio, thresh=0.01):
    """Drop leading/trailing silence so a line starts exactly on its cue."""
    idx = np.where(np.abs(audio) > thresh)[0]
    if not len(idx):
        return audio
    return audio[max(0, idx[0] - 240):idx[-1] + 2400]


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else HERE
    os.makedirs(out_dir, exist_ok=True)
    tl = load_timeline()
    tts = tl.get("tts", {})
    model_dir = os.environ.get("KOKORO_DIR", HERE)
    kokoro = Kokoro(os.path.join(model_dir, "kokoro-v1.0.onnx"),
                    os.path.join(model_dir, "voices-v1.0.bin"))

    sr = 24000
    track = np.zeros(int(tl["duration"] * sr), dtype=np.float32)
    durations = []
    for c in tl["captions"]:
        audio, sr = kokoro.create(c.get("say", c["text"]), voice=tts.get("voice", "af_heart"),
                                  speed=tts.get("speed", 1.0), lang="en-us")
        audio = trim(audio.astype(np.float32))
        dur = len(audio) / sr
        durations.append(round(dur, 3))
        slot = c["e"] - c["s"]
        flag = "  <-- longer than its slot" if dur > slot else ""
        print(f"  {c['s']:5.1f}s  {dur:4.2f}s / {slot:4.2f}s  {c['text'][:50]}{flag}")
        i = int(c["s"] * sr)
        n = min(len(audio), len(track) - i)
        track[i:i + n] += audio[:n]

    sf.write(os.path.join(out_dir, "voiceover.wav"), track, sr)
    with open(os.path.join(HERE, "vo_timing.js"), "w") as f:
        f.write("// Generated by voiceover.py: spoken seconds per caption line.\n")
        f.write(f"globalThis.VO = {json.dumps(durations)};\n")
    print(f"  wrote {os.path.join(out_dir, 'voiceover.wav')} and vo_timing.js")


if __name__ == "__main__":
    main()
